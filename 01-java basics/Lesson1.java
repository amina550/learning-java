public class Lesson1 {
    public static void main(String[]args){
        System.out.println("hello my first code in java");
    }
    
}
//out put: hello my first code in java
/*Here’s what each part does:
- public class Lesson1 defines a class named Lesson1. In Java, the filename must match a public class name, including capitalization.
- public static void main(String[] args) is the program’s starting point. Java runs the instructions inside main first.
- System.out.println(...) prints the text inside the quotation marks, then moves to a new line.
- The semicolon ; marks the end of that instruction.
- Curly braces { } group the contents of the class and the main method.
- // ... starts a comment. Comments are for people reading the code; Java ignores them. */
